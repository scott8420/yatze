import math, sys
# One die, isometric, three faces split by thin gaps; pips are holes (evenodd).
C=(8.0,8.0); s=7.1          # centre vertex and edge reach
c30=math.cos(math.pi/6); 
def P(x,y): return (round(x,3),round(y,3))
T=P(8,8-s); R=P(8+s*c30,8-s/2); L=P(8-s*c30,8-s/2)
B=P(8,8); R2=P(8+s*c30,8+s/2); L2=P(8-s*c30,8+s/2); D=P(8,8+s)
faces={'top':[T,R,B,L],'left':[L,B,D,L2],'right':[B,R,R2,D]}
gap=0.42
def inset(poly,d):
    # move each edge inward by d (convex, clockwise or ccw handled via centroid)
    n=len(poly); cx=sum(p[0] for p in poly)/n; cy=sum(p[1] for p in poly)/n
    lines=[]
    for i in range(n):
        a=poly[i]; b=poly[(i+1)%n]
        ex,ey=b[0]-a[0],b[1]-a[1]; l=math.hypot(ex,ey); nx,ny=-ey/l,ex/l
        mx,my=(a[0]+b[0])/2,(a[1]+b[1])/2
        if (cx-mx)*nx+(cy-my)*ny<0: nx,ny=-nx,-ny
        lines.append(((a[0]+nx*d,a[1]+ny*d),(ex,ey)))
    out=[]
    for i in range(n):
        (p1,d1),(p2,d2)=lines[i-1],lines[i]
        den=d1[0]*d2[1]-d1[1]*d2[0]
        t=((p2[0]-p1[0])*d2[1]-(p2[1]-p1[1])*d2[0])/den
        out.append((p1[0]+d1[0]*t,p1[1]+d1[1]*t))
    return out
def rounded(poly,r):
    # corners rounded with quadratic curves
    n=len(poly); segs=[]
    for i in range(n):
        a=poly[i-1]; b=poly[i]; c=poly[(i+1)%n]
        def toward(p,q,d):
            l=math.hypot(q[0]-p[0],q[1]-p[1]); return (p[0]+(q[0]-p[0])*d/l, p[1]+(q[1]-p[1])*d/l)
        segs.append((toward(b,a,r),b,toward(b,c,r)))
    d=f"M{segs[0][2][0]:.3f} {segs[0][2][1]:.3f}"
    for i in range(1,n+1):
        p,q,e=segs[i%n]
        d+=f"L{p[0]:.3f} {p[1]:.3f}Q{q[0]:.3f} {q[1]:.3f} {e[0]:.3f} {e[1]:.3f}"
    return d+"Z"
def pip(face,u,v,rad):
    # face param: corner0 + u*edge(0->1) + v*edge(0->3), ellipse sampled in face plane
    a,b,_,d=face
    e1=(b[0]-a[0],b[1]-a[1]); e2=(d[0]-a[0],d[1]-a[1])
    pts=[]
    for k in range(20):
        t=2*math.pi*k/20
        uu=u+rad*math.cos(t); vv=v+rad*math.sin(t)
        pts.append((a[0]+e1[0]*uu+e2[0]*vv, a[1]+e1[1]*uu+e2[1]*vv))
    pts=pts[::-1]
    return "M"+"L".join(f"{x:.3f} {y:.3f}" for x,y in pts)+"Z"
paths=[]
pr=0.15
spec={'top':[(0.5,0.5)], 'left':[(0.27,0.27),(0.73,0.73)], 'right':[(0.22,0.22),(0.5,0.5),(0.78,0.78)]}
for name,f in faces.items():
    fi=inset(f,gap/2)
    d=rounded(fi,0.55)
    for (u,v) in spec[name]:
        d+=pip(f,u,v,{'top':0.19,'left':0.14,'right':0.115}[name])
    paths.append(f'    <path fill-rule="evenodd" d="{d}"/>')
if len(sys.argv)>2 and sys.argv[2]=='color':
    shade={'top':'#e5413a','left':'#b3191a','right':'#8a1013'}
    body=[]
    for name,f in faces.items():
        fi=inset(f,gap/2)
        body.append(f'    <path fill="{shade[name]}" d="{rounded(fi,0.55)}"/>')
        for (u,v) in spec[name]:
            body.append(f'    <path fill="#fbf8ef" d="{pip(f,u,v,{"top":0.19,"left":0.14,"right":0.115}[name])}"/>')
